"""Convert Grid's tokens.json (dark theme) to CSS custom properties.

Usage: python3 -I grid/tokens_to_css.py <tokens.json> <artifact version> > grid/tokens.css
"""
import json
import re
import sys

THEME = "dark"
ARTIFACT_URL = "https://claude.ai/artifact/3NFt5Bva1ZnyUnoKLNeBjF"
ALIAS = re.compile(r"^\{([a-z0-9-]+)\}$")


def css_value(value):
    if isinstance(value, dict):
        value = value[THEME]
    match = ALIAS.match(value)
    return f"var(--{match.group(1)})" if match else value


def main(path, version):
    tokens = json.load(open(path))
    sections = [
        ("Colour", tokens["color"]["tokens"]),
        ("Type families", [{"name": f"font-{k}", "value": v} for k, v in tokens["type"]["families"].items()]),
        ("Spacing", tokens["spacing"]["tokens"]),
        ("Radius", tokens["radius"]["tokens"]),
        ("Shadow and glow", tokens["shadow"]["tokens"]),
        ("Opacity", tokens["opacity"]["tokens"]),
        ("Reflection", tokens["reflection"]["tokens"]),
    ]
    out = [
        f"/* Grid design tokens, {THEME} theme only. Generated by grid/tokens_to_css.py from tokens.json in the",
        f"   Grid artifact ({ARTIFACT_URL}, version {version}). Don't edit by hand.",
        "   No @font-face: Saira loads from Google Fonts in index.html. */",
        "",
        ":root {",
    ]
    for i, (title, items) in enumerate(sections):
        if i:
            out.append("")
        out.append(f"  /* {title} */")
        out += [f"  --{t['name']}: {css_value(t['value'])};" for t in items]
    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
